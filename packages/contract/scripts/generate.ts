// Writes the OpenAPI document generated from the Zod schemas, and the TypeScript types the
// client is built on. CI regenerates and fails if the committed output differs.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import { document } from "../src/document.ts";

const root = new URL("../", import.meta.url);
const banner = "// Generated by `pnpm generate` from src/schemas.ts. Do not edit.\n\n";

/** Writes only on change, so watchers (dev servers, tsc --watch) are not woken for nothing. */
async function writeIfChanged(url: URL, content: string): Promise<void> {
  const current = await readFile(url, "utf8").catch(() => null);
  if (current !== content) await writeFile(url, content);
}

await writeIfChanged(new URL("openapi.json", root), `${JSON.stringify(document, null, 2)}\n`);

const ast = await openapiTS(document as Parameters<typeof openapiTS>[0]);
await mkdir(new URL("src/generated/", root), { recursive: true });
await writeIfChanged(new URL("src/generated/openapi.ts", root), banner + astToString(ast));
