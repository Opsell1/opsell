// Writes the OpenAPI documents generated from the Zod schemas, and the TypeScript types the
// clients are built on. CI regenerates and fails if the committed output differs.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import { consoleDocument, document } from "../src/document.ts";

const root = new URL("../", import.meta.url);

/** Writes only on change, so watchers (dev servers, tsc --watch) are not woken for nothing. */
async function writeIfChanged(url: URL, content: string): Promise<void> {
  const current = await readFile(url, "utf8").catch(() => null);
  if (current !== content) await writeFile(url, content);
}

async function generate(spec: object, name: string, source: string): Promise<void> {
  await writeIfChanged(new URL(`${name}.json`, root), `${JSON.stringify(spec, null, 2)}\n`);
  const ast = await openapiTS(spec as Parameters<typeof openapiTS>[0]);
  const banner = `// Generated by \`pnpm generate\` from ${source}. Do not edit.\n\n`;
  await writeIfChanged(new URL(`src/generated/${name}.ts`, root), banner + astToString(ast));
}

await mkdir(new URL("src/generated/", root), { recursive: true });
await generate(document, "openapi", "src/schemas.ts");
await generate(consoleDocument, "console-openapi", "src/console-schemas.ts");
